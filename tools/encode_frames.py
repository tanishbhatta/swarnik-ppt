"""PNG renders -> WebP for the deck, plus the manifest the deck reads.

    python tools/encode_frames.py [--quality 90]

Reads   blender/_frames/stills/*.png          and  blender/_frames/seq_*/NNNN.png
Writes  assets/renders/slide_XX.webp          and  assets/renders/seq_*/NNNN.webp
        assets/renders/manifest.js            (only lists files that exist, so the deck
                                               never requests a missing file)
Prints a size report. Asset budget: 150 MB.
"""
import json
import os
import shutil
import sys
from concurrent.futures import ProcessPoolExecutor

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'blender', '_frames')
DST = os.path.join(ROOT, 'assets', 'renders')

# camera moves: folder -> (from still, to still). Keep in sync with blender/render_all.py SEQS.
SEQS = {
    'seq_01_02': ('slide_01', 'slide_02'),
    'seq_02_03': ('slide_02', 'slide_03'),
    'seq_03_04': ('slide_03', 'slide_04'),
    'seq_06_07': ('slide_06', 'slide_07'),
    'seq_07a_07b': ('slide_07', 'slide_07b'),
    'seq_07_08': ('slide_07b', 'slide_08'),
}


def arg(name, default):
    if name in sys.argv:
        return sys.argv[sys.argv.index(name) + 1]
    return default


Q = int(arg('--quality', 90))
QS = 'lossless'   # stills: lossy WebP turns the dithered near-black desk into visible blocks


def encode(job):
    src, dst, q, size = job
    im = Image.open(src).convert('RGB')
    if size and im.size != size:
        im = im.resize(size, Image.LANCZOS)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if q == 'lossless':
        im.save(dst, 'WEBP', lossless=True, quality=80, method=4)
    else:
        im.save(dst, 'WEBP', quality=q, method=5)
    return os.path.getsize(dst)


def dir_size(path):
    total = 0
    for base, _, files in os.walk(path):
        for f in files:
            total += os.path.getsize(os.path.join(base, f))
    return total


def main():
    os.makedirs(DST, exist_ok=True)
    jobs = []
    stills = {}
    sdir = os.path.join(SRC, 'stills')
    if os.path.isdir(sdir):
        for f in sorted(os.listdir(sdir)):
            if f.endswith('.png'):
                name = f[:-4]
                jobs.append((os.path.join(sdir, f), os.path.join(DST, name + '.webp'), QS, None))
                stills[name] = {'file': name + '.webp', 'w': 1920, 'h': 1080}
    seqs = []
    for folder, (a, b) in SEQS.items():
        d = os.path.join(SRC, folder)
        if not os.path.isdir(d):
            continue
        frames = sorted(f for f in os.listdir(d) if f.endswith('.png'))
        if len(frames) < 2:
            continue
        out = os.path.join(DST, folder)
        if os.path.isdir(out):
            shutil.rmtree(out)
        for i, f in enumerate(frames):
            jobs.append((os.path.join(d, f), os.path.join(out, '%04d.webp' % (i + 1)), Q, None))
        w, h = Image.open(os.path.join(d, frames[0])).size
        seqs.append({'from': a, 'to': b, 'dir': folder, 'frames': len(frames), 'ext': 'webp', 'w': w, 'h': h})

    with ProcessPoolExecutor() as ex:
        sizes = list(ex.map(encode, jobs, chunksize=4))
    print('encoded %d files, %.1f MB' % (len(sizes), sum(sizes) / 1e6))

    screen = None
    sc = os.path.join(DST, 'screen_corners.json')
    if os.path.exists(sc):
        screen = json.load(open(sc))
    manifest = {'stills': stills, 'sequences': seqs, 'screen': screen}
    with open(os.path.join(DST, 'manifest.js'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/encode_frames.py. Lists the render files that exist, '
                'so the deck never asks for a missing one.\n')
        f.write('window.RENDERS = ' + json.dumps(manifest, indent=1) + ';\n')

    print('stills   : %d  (%.1f MB)' % (len(stills), sum(os.path.getsize(os.path.join(DST, s['file'])) for s in stills.values()) / 1e6))
    for s in seqs:
        print('sequence : %-12s %3d frames %dx%d  %.1f MB' % (s['dir'], s['frames'], s['w'], s['h'], dir_size(os.path.join(DST, s['dir'])) / 1e6))
    print('renders total: %.1f MB' % (dir_size(DST) / 1e6))
    print('assets total : %.1f MB  (budget 150 MB)' % (dir_size(os.path.join(ROOT, 'assets')) / 1e6))


if __name__ == '__main__':
    main()
